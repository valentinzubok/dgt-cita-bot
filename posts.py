def get(tag: str) -> Optional[dict]:
    return next((t for t in TEMPLATES if t["tag"] == tag), None)


def title(t: dict) -> str:
    """Первая строка поста без разметки: так шаблон подписан в админке."""
    first = next((line for line in t["text"].splitlines() if line.strip()), t["tag"])
    return re.sub(r"<[^>]+>", "", first).strip()


def fill(text: str, values: dict) -> str:
    for key, value in values.items():
        text = text.replace("{" + key + "}", str(value))
    return text
